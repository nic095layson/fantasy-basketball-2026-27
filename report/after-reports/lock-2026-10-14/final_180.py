#!/usr/bin/env python3
"""The final kit top 180 at the lock, copied row by row from the engine's own board (report/top-200-2026-27.md) with the
move against Version 68's board (board_diff_lock_2026-10-14.json). Writes final-180-kit-2026-10-14.md beside this script."""
import csv, json, os, re
H = os.path.dirname(os.path.abspath(__file__)); K = os.path.dirname(os.path.dirname(H))
D = json.load(open(f"{H}/board_diff_lock_2026-10-14.json", encoding="utf-8"))
before = {n: a for n, a, b in D["moves"]}
# the kit's price: Yahoo's 10/14 lock paste (yahoo-2026-10-14.csv, names already resolved to the pool) — ADP, else XRank
PRICE = {}
for r in csv.DictReader(open(f"{K}/market/yahoo-2026-10-14.csv", encoding="utf-8")):
    PRICE[r["player"]] = (float(r["adp"]), "ADP") if r["adp"] else (float(r["xrank"]), "XR")
rows = []
for l in open(f"{K}/top-200-2026-27.md", encoding="utf-8"):
    m = re.match(r"^\| (\d+) \| ", l)
    if m and int(m.group(1)) <= 180:
        c = [x.strip() for x in l.strip().strip("|").split("|")]
        rows.append(c)
assert [int(r[0]) for r in rows] == list(range(1, 181))
L = ["# Final kit rankings — top 180 at the lock (2026-10-14)", "",
     "Generated by `rank_engine.py` from `projections-2026-27.csv` after the lock re-blend (Yahoo 10/14 + Hashtag 10/14 in the six-way blend; Kornet held; games and minutes ours). Value = per-game z-total × the streaming-credit availability (GP/82 + (1 − GP/82) × 0.20). The kit models health through games played; the deck page's ×0.78 / ×0.85 injury tiers (Kawhi and Davis back at 0.78) live on the draft page, not here. *Move* = places against this morning's board (Version 68); + is up.", "",
     "*Yahoo* = the player's price on your 10/14 lock paste (ADP where Yahoo shows one, else its XRank, marked XR); *mkt #* = his place among all players by that price; *gap* = mkt # minus our rank (+ means the market takes him later than we rank him — a value pick; − means earlier).", "",
     "| # | Player | Tm | Pos | GP | pts/reb/ast/stl/blk/3pm | FG%/FT% | value | move | Yahoo | mkt # | gap |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
MKT = {n: i + 1 for i, (n, _) in enumerate(sorted(PRICE.items(), key=lambda kv: (kv[1][0], kv[0])))}
for r in rows:
    rk, n = int(r[0]), r[1]
    mv = before.get(n)
    mvs = "—" if mv is None else f"{mv - rk:+d}"
    pr = PRICE.get(n)
    ps = "—" if pr is None else (f"{pr[0]:g}" if pr[1] == "ADP" else f"{pr[0]:g} XR")
    mk = MKT.get(n)
    L.append(f"| {rk} | {n} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[8]} | {mvs} | {ps} | {mk or '—'} | {'—' if mk is None else f'{mk - rk:+d}'} |")
open(f"{H}/final-180-kit-2026-10-14.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote", len(rows), "rows")
